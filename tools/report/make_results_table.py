#!/usr/bin/env python3
"""Generate the acceptance results table for the report from the recorded run.

The report used to carry these 26 rows typed out by hand. They drifted: the table described the
run of one day while the figure printed beside it - which reads the same JSON this script does -
described another. Anything transcribed by hand goes stale the moment the suite is re-run, and
nothing warns you, so the table is generated instead.

    ./robofetch_venv/bin/python tools/report/make_results_table.py

Writes report/generated/acceptance-table.tex, which the report pulls in with \\input. The file
holds the data rows and nothing else: the longtable environment, the column widths, the header,
the caption and the \\label all stay in the .tex, so the table still reads as a table there and
the cross-reference is where a reader looks for it.
"""
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
DATA = HERE / "data" / "acceptance_results.json"
OUT = HERE.parent.parent / "report" / "generated" / "acceptance-table.tex"

# Order matters: the backslash has to be replaced first or it would escape the escapes.
ESCAPES = [
    ("\\", r"\textbackslash{}"),
    ("&", r"\&"), ("#", r"\#"), ("$", r"\$"),
    ("{", r"\{"), ("}", r"\}"),
    ("_", r"\_"), ("%", r"\%"),
    ("~", r"\textasciitilde{}"),
    ("^", r"\textasciicircum{}"),
]
# '>' and '<' are deliberately NOT escaped. The preamble loads T1 fontenc, under which they
# render as themselves, and the evidence strings are full of "->" arrows that read correctly.


def escape(text):
    for old, new in ESCAPES:
        text = text.replace(old, new)
    return text


def tidy(evidence):
    """Shorten what is noise in a printed report rather than evidence."""
    # The absolute database path is the developer's home directory - it identifies a machine and
    # a username, and says nothing about whether the check passed.
    return evidence.replace(str(pathlib.Path.home() / "robofetch_ws") + "/", "")


def main():
    with open(DATA) as handle:
        results = json.load(handle)

    lines = [
        "% Generated by tools/report/make_results_table.py - do not edit by hand.",
        "% Regenerate after any acceptance run:",
        "%     ./robofetch_venv/bin/python tools/report/make_results_table.py",
        "% Data rows only - the surrounding longtable lives in the report itself.",
    ]

    for row in results:
        # The JSON writes descriptions in lower case because they are printed to a terminal; the
        # report capitalises them, so the sentence reads as a sentence on the page.
        check = row["description"]
        check = check[:1].upper() + check[1:]
        lines.append("%s & %s & %s \\\\" % (
            escape(row["requirement"]),
            escape(check),
            escape(tidy(row["evidence"])),
        ))

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")

    passed = sum(1 for r in results if r["passed"])
    print(f"wrote {OUT.relative_to(HERE.parent.parent)}")
    print(f"  {len(results)} checks, {passed} passed")
    if passed != len(results):
        failed = [r["requirement"] for r in results if not r["passed"]]
        print(f"  WARNING: the recorded run was not clean - failed: {', '.join(failed)}")


if __name__ == "__main__":
    main()
